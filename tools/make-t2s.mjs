// Builds t2s.js: a character map from Traditional (Taiwan) to Simplified, used only to look up pinyin.
import * as OpenCC from "opencc-js";
import { writeFile } from "node:fs/promises";
const conv = OpenCC.Converter({ from: "tw", to: "cn" });
let from = "", to = "";
for (let cp = 0x3400; cp <= 0x9fff; cp++) {
  const c = String.fromCodePoint(cp);
  const s = conv(c);
  if (s !== c && [...s].length === 1) { from += c; to += s; }
}
await writeFile("t2s.js", `// Generated by tools/make-t2s.mjs from OpenCC (Apache-2.0). Traditional -> Simplified, one character each.\nexport const T = ${JSON.stringify(from)};\nexport const S = ${JSON.stringify(to)};\n`);
console.log(from.length, "pairs");
